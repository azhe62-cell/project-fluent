/**
 * Bundles the trusted server code (src/server + the src/engine it uses) into one ES module the Edge
 * Functions (Deno) import, so production runs the exact code the Vitest suites exercise.   npm run build:edge
 */
import { build } from 'esbuild';
import { rmSync } from 'node:fs';

rmSync('supabase/functions/_shared/engine.js', { force: true });   // superseded by server.js
await build({
  entryPoints: ['src/server/index.ts'],
  outfile: 'supabase/functions/_shared/server.js',
  bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
  alias: { '@': './src' },
  banner: { js: '// GENERATED by scripts/build-edge.ts from src/server + src/engine — do not edit.\n// @ts-nocheck' },
});
console.log('server bundle written');
