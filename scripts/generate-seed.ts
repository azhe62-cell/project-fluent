/**
 * Generates supabase/seed.sql from the SAME content modules the app and unit tests use,
 * so database content can never drift from what the tests verified.
 *   npm run seed:generate
 * Seeds are insert-only (ON CONFLICT DO NOTHING): published versions are immutable. To change
 * content, bump the test version instead of editing a published one.
 */
import { writeFileSync } from 'node:fs';
import { publishedTests, practiceBank } from '../src/content/index.public';
import { allAnswerKeys } from '../src/content/index.keys';
import type { PublicTest } from '../src/engine/types';

const lit = (s: string | null | undefined) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`);
const js = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`;
const arr = (a: string[]) => `ARRAY[${a.map(lit).join(',')}]::text[]`;

const bankTest: PublicTest = {
  id: 'test-bank-reading-01', slug: 'practice-bank-reading', title: 'Reading practice bank',
  description: 'Hidden bank of short items used for targeted practice. Not listed in the catalogue.',
  assessmentType: 'reading', version: 1, durationSeconds: 3600,
  scoringNote: 'Practice bank — items are graded individually.',
  passages: practiceBank.passages, questions: practiceBank.questions,
  sections: [{ id: 'bank-s1', title: 'Practice bank', passageId: practiceBank.passages[0].id, groups: [] }],
};

const out: string[] = ['-- GENERATED by scripts/generate-seed.ts — do not edit by hand.', '-- Original demo content only. Contains NO learner accounts or fake statistics.', 'begin;'];

for (const [t, listed] of [...publishedTests.map((x) => [x, true] as const), [bankTest, false] as const]) {
  const vid = `${t.id}@v${t.version}`;
  out.push(`insert into public.tests (id, slug, title, description, assessment_type, publication_status, is_listed, current_version) values (${lit(t.id)}, ${lit(t.slug)}, ${lit(t.title)}, ${lit(t.description)}, ${lit(t.assessmentType)}, 'published', ${listed}, ${t.version}) on conflict (id) do nothing;`);
  out.push(`insert into public.test_versions (id, test_id, version_number, duration_seconds, scoring_configuration, section_configuration, public_content, published_at) values (${lit(vid)}, ${lit(t.id)}, ${t.version}, ${t.durationSeconds}, ${js({ scoringVersion: 'reading-raw-v1' })}, ${js(t.sections)}, ${js(t)}, now()) on conflict (id) do nothing;`);

  const sectionOf = new Map<string, string>();
  t.sections.forEach((s, i) => {
    out.push(`insert into public.test_sections (id, test_version_id, section_type, title, instructions, display_order) values (${lit(s.id)}, ${lit(vid)}, ${lit(t.assessmentType)}, ${lit(s.title)}, null, ${i + 1}) on conflict (id) do nothing;`);
    s.groups.flatMap((g) => g.questionIds).forEach((qid) => sectionOf.set(qid, s.id));
  });
  const passageSection = new Map(t.sections.map((s) => [s.passageId, s.id]));
  for (const p of t.passages) {
    const sec = passageSection.get(p.id) ?? t.sections[0].id;
    out.push(`insert into public.passages (id, section_id, title, content, metadata) values (${lit(p.id)}, ${lit(sec)}, ${lit(p.title)}, ${js(p.paragraphs)}, ${js({ kicker: p.kicker ?? null })}) on conflict (id) do nothing;`);
  }
  for (const q of t.questions) {
    const sec = sectionOf.get(q.id) ?? t.sections[0].id;
    out.push(`insert into public.questions (id, section_id, passage_id, question_type, prompt, instructions, options, display_number, marks, skill_tags, topic_tags, difficulty_estimate, content_version, publication_status, review_status) values (${lit(q.id)}, ${lit(sec)}, ${lit(q.passageId)}, ${lit(q.type)}, ${lit(q.prompt)}, ${lit(q.instructions)}, ${q.options ? js(q.options) : 'null'}, ${q.number}, ${q.marks}, ${arr(q.skillTags)}, ${arr(q.topicTags)}, ${q.difficulty}, ${q.version}, 'published', 'approved') on conflict (id) do nothing;`);
  }
}
for (const k of allAnswerKeys)
  out.push(`insert into public.answer_keys (question_id, version, marks, rule, display, explanation) values (${lit(k.questionId)}, ${k.version}, ${k.marks}, ${js(k.rule)}, ${lit(k.display)}, ${lit(k.explanation)}) on conflict (question_id, version) do nothing;`);

out.push('commit;', '');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), out.join('\n'));
console.log(`seed.sql written: ${publishedTests.length + 1} tests, ${allAnswerKeys.length} answer keys`);
